-- TOTAL
create or replace function public.recalc_order_total(p_order_id bigint)
returns numeric language plpgsql security invoker set search_path=public
as $$ declare v_total numeric(12,2); begin
  select coalesce(sum(quantity*unit_price),0) into v_total from public.order_items where order_id=p_order_id;
  update public.orders set total=v_total,updated_at=now() where id=p_order_id;
  return v_total;
end $$;
grant execute on function public.recalc_order_total(bigint) to authenticated;

