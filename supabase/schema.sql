-- ORDERS
create table public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique default ('ORD-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10))),
  customer_id uuid references public.profiles(id) on delete set null,
  cashier_id uuid references public.profiles(id) on delete set null,
  customer_name text,
  customer_phone text,
  address text,
  latitude double precision,
  longitude double precision,
  total numeric(12,2) not null default 0,
  payment_method text not null check(payment_method in ('cash','qris','transfer')),
  payment_status text not null default 'pending' check(payment_status in ('pending','paid','rejected')),
  status text not null default 'pending' check(status in ('pending','confirmed','preparing','ready','completed','cancelled')),
  ordered_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.orders enable row level security;
drop policy if exists orders_customer_select on public.orders;
create policy orders_customer_select on public.orders for select to authenticated using(customer_id=auth.uid());
drop policy if exists orders_customer_insert on public.orders;
create policy orders_customer_insert on public.orders for insert to authenticated with check(customer_id=auth.uid() and status='pending');
drop policy if exists orders_cashier_select on public.orders;
create policy orders_cashier_select on public.orders for select to authenticated using(public.current_user_role()='cashier');
drop policy if exists orders_cashier_update on public.orders;
create policy orders_cashier_update on public.orders for update to authenticated using(public.current_user_role()='cashier') with check(public.current_user_role()='cashier');

-- ORDER ITEMS
create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  menu_id bigint not null references public.menu(id),
  quantity integer not null check(quantity>0),
  unit_price numeric(12,2) not null check(unit_price>=0),
  created_at timestamptz not null default now()
);
alter table public.order_items enable row level security;
drop policy if exists order_items_customer_select on public.order_items;
create policy order_items_customer_select on public.order_items for select to authenticated using(exists(select 1 from public.orders o where o.id=order_items.order_id and o.customer_id=auth.uid()));
drop policy if exists order_items_customer_insert on public.order_items;
create policy order_items_customer_insert on public.order_items for insert to authenticated with check(exists(select 1 from public.orders o where o.id=order_items.order_id and o.customer_id=auth.uid()));
drop policy if exists order_items_cashier_select on public.order_items;
create policy order_items_cashier_select on public.order_items for select to authenticated using(public.current_user_role()='cashier');
drop policy if exists order_items_cashier_insert on public.order_items;
create policy order_items_cashier_insert on public.order_items for insert to authenticated with check(public.current_user_role()='cashier');

